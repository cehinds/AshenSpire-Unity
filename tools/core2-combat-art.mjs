#!/usr/bin/env node
// core2-combat-art.mjs — the Core 2 combat screen's art index and its provenance check (port plan phase 6).
//
//   node tools/core2-combat-art.mjs <js-checkout> [--check] [--allow-unpinned]
//
// 1. Writes Unity/Assets/AshenSpire/Resources/Core2Ui/card-art.json: each Core 2 card's painting, as the JS build picks
//    it — src/ui/cardArtComposition.js simpleCardArt(definition) → its approved component art code (O00, O44, …) — mapped
//    to the PNG PR #72 rendered for that code from the same card cutouts (Resources/Art/js1815/cards/art-*). A card JS
//    paints with no component art (it falls back to an outline icon) has no entry, and its art window stays dark.
// 2. Checks every reused Art/js1815/{combat,ui,cards} PNG against the pinned build's art cache: each provenance row's
//    source sha256 must equal the file in .art-cache/ashenspire-hd-assets-v24 (the 1854 pack), so the 1815-era imports
//    are byte-identical inputs at the pin. Sources JS generates from code (combat sigils) are checked against their
//    JS source files instead. Without the cache the check reports the rows it could not reach and fails.
// Read-only against the JS checkout (refuses a dirty tree or a commit other than the SPEC §0.2 pin).
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {root, parseArgs, jsIdentity, requirePin, jsonText, sortKeys} from './js-core2-shared.mjs';

const USAGE = 'usage: node tools/core2-combat-art.mjs <js-checkout> [--check] [--allow-unpinned]';
const args = parseArgs(process.argv.slice(2), USAGE);
let identity;
try { identity = jsIdentity(args.js); requirePin(identity, args.allowUnpinned); }
catch (error) { console.error(`core2-combat-art: ${error.message}`); process.exit(1); }

const OUT = 'Unity/Assets/AshenSpire/Resources/Core2Ui/card-art.json';
const ART = 'Unity/Assets/AshenSpire/Resources/Art/js1815';
const CACHE = join(args.js, '.art-cache/ashenspire-hd-assets-v24');
// PR #72's renders of each component art code (Resources/Original/illustrated-reference-1815.json `artwork`, branch
// feature/intelligent-einstein-i1dpk2): the card cutout layers composited in Chromium at 340x304.
const CODE_ART = {
  O00: 'Art/js1815/cards/art-cc839d43cd2202c2', O11: 'Art/js1815/cards/art-00926959ac083e89', O44: 'Art/js1815/cards/art-ec78a61818af9b92',
  L40: 'Art/js1815/cards/art-95e76b6beb925470', Y00: 'Art/js1815/cards/art-12b5a6f1d794ba36', I00: 'Art/js1815/cards/art-70445d094f3b9a14',
  F00: 'Art/js1815/cards/art-f6242a1c78147328', G00: 'Art/js1815/cards/art-239cf97af8ec3981',
};
const sha = file => createHash('sha256').update(readFileSync(file)).digest('hex');
const failures = [];
let checks = 0;

// ---- 1. the card art index ------------------------------------------------------------------------------------------
const {simpleCardArt} = await import(join(args.js, 'src/ui/cardArtComposition.js'));
const cards = JSON.parse(readFileSync(join(root, 'GameContent/Unity/Core2/pack/cards.json'), 'utf8'));
const index = {};
for (const def of cards) {
  const art = simpleCardArt(def, {ref: {cardId: def.id}});
  const code = art?.componentArt?.code ?? null;
  if (!code) continue;
  if (!CODE_ART[code]) { failures.push(`card ${def.id}: art code ${code} has no imported render`); continue; }
  index[def.id] = {code, resource: CODE_ART[code]};
}
for (const resource of new Set(Object.values(CODE_ART))) {
  if (existsSync(join(root, 'Unity/Assets/AshenSpire/Resources', resource + '.png'))) checks++;
  else failures.push(`${resource}.png is missing`);
}
const text = jsonText({
  _: 'Generated by tools/core2-combat-art.mjs from the JS checkout at the SPEC pin; do not edit.',
  js: {commit: identity.commit, build: identity.build}, source: 'src/ui/cardArtComposition.js simpleCardArt → componentArt.code', cards: sortKeys(index),
});
const outPath = join(root, OUT);
if (args.check) {
  if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== text) failures.push(`${OUT} is stale; run node tools/core2-combat-art.mjs <js-checkout>`);
  else checks++;
} else if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== text) writeFileSync(outPath, text);

// ---- 2. provenance against the pinned build -------------------------------------------------------------------------
// The imports were made at build 1815 (JS 0029e160). A painted source is checked by its sha256 against the 1854 art
// cache; a source JS draws from code (a CSS rule, an SVG tag symbol, the action frame, the combat sigils) by its file
// being unchanged between 1815 and the pin; a Chromium render of the card cutouts by every cutout being byte-identical
// between the 1815 tree (git) and the 1854 cache (the pin moved them out of the repository into the cache).
const BUILD_1815 = '0029e160b93243eb437e809cbb0df7ef8824aa14';
const git = (...rest) => execFileSync('git', ['-C', args.js, ...rest], {maxBuffer: 1 << 28});
const unchanged = file => { try { git('diff', '--quiet', BUILD_1815, identity.commit, '--', file); return true; } catch { return false; } };
let cutoutsSame = null;
function cutoutsUnchanged() {
  if (cutoutsSame !== null) return cutoutsSame;
  const names = git('ls-tree', '--name-only', `${BUILD_1815}:assets-display/card-cutouts`).toString().trim().split('\n');
  cutoutsSame = names.every(name => {
    const cache = join(CACHE, 'common/assets-display/card-cutouts', name);
    return existsSync(cache) && createHash('sha256').update(git('show', `${BUILD_1815}:assets-display/card-cutouts/${name}`)).digest('hex') === sha(cache);
  });
  return cutoutsSame;
}
const CODE_SOURCES = {svg: 'src/ui/components/cardTagSymbols.js'};
function cached(path) {
  const rel = path.replace(/^\.art-cache\/hd-assets-v23\//, '').replace(/^high\//, '');
  return [join(CACHE, 'high', rel), join(CACHE, 'common', rel), join(CACHE, 'light', rel)].find(existsSync) || null;
}
for (const kind of ['combat', 'ui', 'cards']) {
  const prov = JSON.parse(readFileSync(join(root, ART, kind, 'provenance.json'), 'utf8'));
  for (const asset of prov.assets) {
    const png = join(root, 'Unity/Assets/AshenSpire/Resources', asset.resource + '.png');
    if (!existsSync(png)) continue; // only the files this branch carries are checked
    if (asset.outputSha256 && sha(png) !== asset.outputSha256) { failures.push(`${asset.resource}.png differs from its provenance output sha256`); continue; }
    if (asset.conversion === 'chromium-rendered') {
      if (cutoutsUnchanged()) checks++; else failures.push(`${asset.resource}: the card cutouts it renders changed between 1815 and the pin`);
      continue;
    }
    const sources = asset.sources || [{path: asset.sourcePath || asset.source, sha256: asset.sourceSha256}];
    for (const source of sources) {
      if (!source.path) continue;
      const file = source.sha256 ? cached(source.path) : null;
      if (file) { if (sha(file) === source.sha256) checks++; else failures.push(`${asset.resource}: source ${source.path} changed at the pin`); continue; }
      const code = CODE_SOURCES[source.path] ?? source.path.split(' ')[0];
      if (/\.(js|css)$/.test(code) && unchanged(code)) checks++;
      else failures.push(`${asset.resource}: source ${source.path} is neither in the pinned art cache nor unchanged code`);
    }
  }
}

for (const failure of failures) console.error(failure);
if (failures.length) { console.log(`core2-combat-art: ${checks} passed, ${failures.length} failed`); process.exit(1); }
console.log(`core2-combat-art: OK — ${checks} checks passed`);

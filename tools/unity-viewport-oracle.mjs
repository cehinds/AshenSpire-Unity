#!/usr/bin/env node
// unity-viewport-oracle.mjs — answers from the JS game's OWN layout decider, for UnityTests/Viewport.
//
//   node tools/unity-viewport-oracle.mjs <js-checkout>
//
// Reads layoutForCap() out of <js>/src/main.js and formFactorFor() from
// <js>/src/ui/models/FormFactorModel.js, runs them with balance.ui.uiScale from the committed
// snapshot (GameContent/Unity/JsUi/extracted/balance-ui.json) over a grid of viewports and the
// named UI-size caps, and writes UnityTests/Viewport/js-layout-oracle.json. The Viewport suite
// then checks ViewportLayout.Resolve against every row, so the C# port cannot drift from JS
// without a red test. Re-run after `unity-ui-tokens.mjs --import`. Read-only on the JS checkout.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const js = process.argv[2];
if (!js) { console.error('usage: node tools/unity-viewport-oracle.mjs <js-checkout>'); process.exit(2); }

const main = readFileSync(join(js, 'src/main.js'), 'utf8');
const start = main.indexOf('function layoutForCap(');
if (start < 0) { console.error('unity-viewport-oracle: layoutForCap not found in src/main.js'); process.exit(2); }
let depth = 0, end = main.indexOf('{', start);
for (; end < main.length; end++) { if (main[end] === '{') depth++; else if (main[end] === '}' && --depth === 0) break; }
const source = main.slice(start, end + 1);
const balance = JSON.parse(readFileSync(join(ROOT, 'GameContent/Unity/JsUi/extracted/balance-ui.json'), 'utf8'));
const UI = { uiScale: balance.uiScale };
// eslint-disable-next-line no-new-func
const layoutForCap = new Function('UI', `${source}; return layoutForCap;`)(UI);
const { formFactorFor } = await import(pathToFileURL(join(js, 'src/ui/models/FormFactorModel.js')).href);

const widths = [320, 360, 375, 390, 412, 430, 480, 500, 520, 521, 600, 667, 768, 800, 834, 844, 896, 1024, 1180, 1280, 1366, 1440, 1600, 1920, 2560, 3440];
const heights = [320, 340, 360, 390, 412, 430, 464, 465, 600, 640, 667, 720, 730, 768, 780, 800, 844, 900, 915, 1024, 1080, 1194, 1440];
const caps = [['auto', null], ...Object.entries(balance.uiScale.named)];
const rows = [];
for (const [size, cap] of caps)
  for (const w of widths)
    for (const h of heights) {
      const a = layoutForCap(cap == null ? Infinity : cap, w, h);
      rows.push([cap == null ? 0 : cap, w, h, a.zoom, a.narrow ? 1 : 0, a.compact ? 1 : 0, a.short ? 1 : 0, formFactorFor(w, h, balance.uiScale.formFactor)]);
    }
const out = join(ROOT, 'UnityTests/Viewport/js-layout-oracle.json');
const head = readFileSync(join(ROOT, 'GameContent/Unity/JsUi/manifest.json'), 'utf8');
const manifest = JSON.parse(head);
writeFileSync(out, JSON.stringify({ _: 'GENERATED by tools/unity-viewport-oracle.mjs from the JS layoutForCap/formFactorFor. Do not edit.', commit: manifest.commit, build: manifest.build, columns: ['cap (0 = auto)', 'width', 'height', 'zoom', 'narrow', 'compact', 'short', 'formFactor'], rows }).replace(/\],\[/g, '],\n[') + '\n');
console.log(`unity-viewport-oracle: wrote ${rows.length} rows to UnityTests/Viewport/js-layout-oracle.json`);
